"""Generates frontend/js/config.js from .env, so the real Gemini API key
never has to be committed to git. Run this once after cloning the repo
(with your own .env filled in) and again any time .env changes.

This is NOT a build step the deployed site runs -- it's a local generation
step you run before `firebase deploy`, same as any other static site. The
output, config.js, is gitignored; only this script and config.example.js
(the template) are committed.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV_PATH = os.path.join(ROOT, ".env")
OUT_PATH = os.path.join(ROOT, "frontend", "js", "config.js")


def load_env(path):
    env = {}
    if not os.path.exists(path):
        return env
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            env[key.strip()] = value.strip()
    return env


def main():
    env = load_env(ENV_PATH)
    api_key = env.get("GEMINI_API_KEY")
    model = env.get("GEMINI_MODEL", "gemini-3.8-flash")

    if not api_key or api_key == "YOUR_GEMINI_API_KEY_HERE":
        raise SystemExit(
            f"No real GEMINI_API_KEY found in {ENV_PATH}.\n"
            "Copy .env.example to .env and fill in a real key from "
            "https://aistudio.google.com/apikey before running this script."
        )

    content = f'''/**
 * GENERATED by scripts/generate_config.py from .env -- do not edit by hand,
 * and do not commit this file (it is gitignored). See config.example.js
 * for the template, and .env.example for the variables this reads.
 *
 * The Gemini API key below is necessarily visible to anyone who views the
 * deployed site's JS -- there is no backend to hide it behind in this
 * zero-billing, static-hosting deployment. Mitigate by restricting the
 * key's Application restrictions to your deployed domain in Cloud Console
 * if that option is available for your key type.
 */
export const GEMINI_API_KEY = "{api_key}";
export const GEMINI_MODEL = "{model}";
export const GEMINI_API_URL =
  `https://generativelanguage.googleapis.com/v1beta/models/${{GEMINI_MODEL}}:generateContent`;
'''

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Wrote {OUT_PATH} from {ENV_PATH}")


if __name__ == "__main__":
    main()
